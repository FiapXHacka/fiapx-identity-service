-- identity_db — owner: identity-service. Applied by the EF Core migrations; kept as the reviewable DDL (ADR-0009).

CREATE TABLE users (
    id             uuid        NOT NULL,                  -- uuid v7 generated by the application
    email          text        NOT NULL,
    name           text        NOT NULL,
    password_hash  text        NOT NULL,                  -- PasswordHasher<T> (PBKDF2)
    created_at     timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT pk_users PRIMARY KEY (id),
    CONSTRAINT users_email_format CHECK (position('@' in email) > 1)
);
CREATE UNIQUE INDEX ux_users_email_lower ON users (lower(email));

CREATE TABLE outbox_messages (
    id            uuid        NOT NULL,                  -- = CloudEvent.id
    type          text        NOT NULL,                  -- routing key, e.g. user.registered
    payload       jsonb       NOT NULL,                  -- full CloudEvent
    occurred_at   timestamptz NOT NULL DEFAULT now(),
    published_at  timestamptz,
    attempts      int         NOT NULL DEFAULT 0,
    CONSTRAINT pk_outbox_messages PRIMARY KEY (id)
);
CREATE INDEX ix_outbox_pending ON outbox_messages (occurred_at) WHERE published_at IS NULL;
